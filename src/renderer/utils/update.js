import { httpGet } from './request'
import { compareVer } from '@common/utils'
const releaseRepository = 'Tingfe/lx-music-desktop'
const latestReleaseUrl = `https://api.github.com/repos/${releaseRepository}/releases/latest`
const releasesUrl = `https://api.github.com/repos/${releaseRepository}/releases`

const request = async(url, retryNum = 0) => {
  return new Promise((resolve, reject) => {
    httpGet(url, {
      timeout: 10000,
    }, (err, resp, body) => {
      if (err || resp.statusCode != 200) {
        ++retryNum >= 3
          ? reject(err || new Error(resp.statusMessage || resp.statusCode))
          : request(url, retryNum).then(resolve).catch(reject)
      } else resolve(body)
    })
  })
}

export const getVersionInfo = async(includePreRelease = false) => {
  let release = await request(latestReleaseUrl)
  if (includePreRelease) {
    const releases = await request(releasesUrl)
    // Only recognize previews generated by this fork. Older upstream-style tags such
    // as `test-v4` cannot be compared safely by the version checker.
    if (!Array.isArray(releases)) throw new Error('Invalid release list')
    const previews = releases.filter(item => !item.draft && item.prerelease && /^v\d+\.\d+\.\d+-test\.\d+$/.test(item.tag_name))
    for (const preview of previews) {
      const baseVersion = preview.tag_name.replace(/^v/, '').replace(/-test\.\d+$/, '')
      const selectedVersion = release.tag_name.replace(/^v/, '').replace(/-test\.\d+$/, '')
      if (compareVer(selectedVersion, baseVersion) < 0) release = preview
    }
  }
  const version = release?.tag_name?.replace(/^v/, '').replace(/-test\.\d+$/, '')
  if (!/^\d+\.\d+\.\d+$/.test(version) || release.draft) throw new Error('Invalid release version')
  return {
    version,
    desc: release.body || '',
    history: [],
    releaseUrl: `https://github.com/${releaseRepository}/releases/tag/${encodeURIComponent(release.tag_name)}`,
    manualDownload: !!release.prerelease,
  }
}

